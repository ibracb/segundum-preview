package umu.aadd.segundum.modelo;

/**
 * Enum que modela los posibles estados de un producto.
 */
public enum EstadoProducto {

	/**
	 * Representa que el producto está en estado "nuevo".
	 */
	NUEVO,

	/**
	 * Representa que el producto está en estado "como nuevo".
	 */
	COMO_NUEVO,

	/**
	 * Representa que el producto está en "buen estado".
	 */
	BUEN_ESTADO,

	/**
	 * Representa que el producto está en estado "aceptable".
	 */
	ACEPTABLE,

	/**
	 * Representa que el producto está "para piezas".
	 */
	PARA_PIEZAS,

	/**
	 * Representa que el producto está "para reparar".
	 */
	REPARAR;
}
